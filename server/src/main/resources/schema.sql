CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(512) NOT NULL,
  registration_date TIMESTAMP WITHOUT TIME ZONE,
  state VARCHAR(20),
  CONSTRAINT pk_user PRIMARY KEY (id),
  CONSTRAINT UQ_USER_EMAIL UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    description VARCHAR(1000),
    requestor_id BIGINT,
    created TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_request PRIMARY KEY (id),
    CONSTRAINT fk_request_requestor FOREIGN KEY (requestor_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    item_id BIGINT,
    request_id BIGINT,
    CONSTRAINT pk_answer PRIMARY KEY (id),
    CONSTRAINT fk_answer_item FOREIGN KEY (item_id) REFERENCES items(id),
    CONSTRAINT fk_answer_request FOREIGN KEY (request_id) REFERENCES requests(id)
);

CREATE TABLE IF NOT EXISTS comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    text VARCHAR(2000) NOT NULL,
    item_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_comment PRIMARY KEY (id),
    CONSTRAINT fk_comment_item FOREIGN KEY (item_id) REFERENCES items(id),
    CONSTRAINT fk_comment_author FOREIGN KEY (author_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  name VARCHAR(255) NOT NULL,
  description VARCHAR(1000),
  available BOOLEAN,
  owner_id BIGINT NOT NULL,
  request_id BIGINT,
  CONSTRAINT pk_item PRIMARY KEY (id),
  CONSTRAINT fk_item_owner FOREIGN KEY (owner_id) REFERENCES users(id),
  CONSTRAINT fk_item_request FOREIGN KEY (request_id) REFERENCES requests(id)
);

CREATE TABLE IF NOT EXISTS tags (
  item_id BIGINT NOT NULL,
  name VARCHAR(255) NOT NULL,
  CONSTRAINT pk_tag PRIMARY KEY (item_id, name),
  CONSTRAINT fk_item_tags FOREIGN KEY (item_id) REFERENCES items(id)
);

CREATE TABLE IF NOT EXISTS item_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    text VARCHAR(2000) NOT NULL,
    item_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE,
    CONSTRAINT pk_item_note PRIMARY KEY (id),
    CONSTRAINT fk_item_note_item FOREIGN KEY (item_id) REFERENCES items(id)
);

CREATE TABLE IF NOT EXISTS bookings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
 start_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 end_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
 item_id BIGINT NOT NULL,
 booker_id BIGINT NOT NULL,
 status VARCHAR(20) NOT NULL,
 CONSTRAINT pk_booking PRIMARY KEY (id),
 CONSTRAINT fk_booking_item FOREIGN KEY (item_id) REFERENCES items(id),
 CONSTRAINT fk_booking_booker FOREIGN KEY (booker_id) REFERENCES users(id)
);